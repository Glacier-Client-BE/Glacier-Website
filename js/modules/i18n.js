// FAQ answers, category names, and a couple of dynamic-section strings live
// in a separate module (js/modules/i18nFaq.js) rather than inline above,
// since they're large HTML blobs. Merge them in here; es-MX reuses the es
// FAQ text verbatim, matching how the rest of its strings mirror es.
for (const lang of Object.keys(FAQ_STRINGS)) {
    Object.assign(STRINGS[lang] || (STRINGS[lang] = {}), FAQ_STRINGS[lang]);
}
if (FAQ_STRINGS.es) Object.assign(STRINGS['es-MX'] || (STRINGS['es-MX'] = {}), FAQ_STRINGS.es);

const LANG_KEY = 'gc-lang';

export function t(lang, key) {
    if (STRINGS[lang] && STRINGS[lang][key]) return STRINGS[lang][key];
    if (STRINGS.en && STRINGS.en[key]) return STRINGS.en[key];
    return '';
}

export function currentLang() {
    let saved = null;
    try { saved = localStorage.getItem(LANG_KEY); } catch { }
    const lang = saved || detectLang();
    return STRINGS[lang] ? lang : 'en';
}

// Maps a browser locale like "pt-BR" or "fil" onto the closest supported code.
function detectLang() {
    const known = new Set(LANGS.map(l => l[0]));
    for (let cand of navigator.languages || [navigator.language || 'en']) {
        if (known.has(cand)) return cand;
        if (cand === 'fil') return 'tl';
        cand = cand.split('-')[0];
        if (known.has(cand)) return cand;
    }
    return 'en';
}

export function applyLang(lang) {
    if (!STRINGS[lang]) lang = 'en';
    document.documentElement.lang = lang;
    // Plain-text swaps. Using textContent keeps any injected markup inert.
    for (const el of document.querySelectorAll('[data-i18n]')) {
        el.textContent = t(lang, el.dataset.i18n);
    }
    // HTML-aware swaps for keys whose translations carry inline markup
    // (<code>, <strong>, <a>, …). Keys must be fully trusted translations.
    for (const el of document.querySelectorAll('[data-i18n-html]')) {
        el.innerHTML = t(lang, el.dataset.i18nHtml);
    }
    for (const el of document.querySelectorAll('[data-i18n-ph]')) {
        el.setAttribute('placeholder', t(lang, el.dataset.i18nPh));
    }
    for (const el of document.querySelectorAll('[data-i18n-aria]')) {
        el.setAttribute('aria-label', t(lang, el.dataset.i18nAria));
    }
    try { localStorage.setItem(LANG_KEY, lang); } catch { }
    syncLangDropdown(lang);

    // Data-driven content (mods, FAQ, downloads) is rendered from JSON and
    // can't use data-i18n directly; main.js listens for this to re-render it.
    document.dispatchEvent(new CustomEvent('gc:langchange', { detail: { lang } }));
}

// Reflect the active language in the custom dropdown: trigger label + the
// highlighted option. Safe to call before the dropdown is wired up.
function syncLangDropdown(lang) {
    const code = STRINGS[lang] ? lang : 'en';
    const label = (LANGS.find(l => l[0] === code) || LANGS[0])[1];
    const labelEl = document.getElementById('currentLangLabel');
    if (labelEl) labelEl.textContent = label;
    for (const opt of document.querySelectorAll('.lang-dropdown-option')) {
        opt.classList.toggle('is-active', opt.dataset.value === code);
        opt.setAttribute('aria-selected', String(opt.dataset.value === code));
    }
}

function closeLangDropdown(root) {
    if (!root) return;
    root.classList.remove('is-open');
    const trigger = root.querySelector('.lang-dropdown-trigger');
    if (trigger) trigger.setAttribute('aria-expanded', 'false');
}

export function setupI18n() {
    const root = document.getElementById('langDropdown');
    const trigger = document.getElementById('langDropdownTrigger');
    const menu = document.getElementById('langDropdownMenu');

    if (root && trigger && menu) {
        // Build the option list once from the LANGS table.
        let opts = '';
        for (const [code, label] of LANGS) {
            opts += '<button type="button" class="lang-dropdown-option" role="option"'
                + ' data-value="' + code + '" aria-selected="false">'
                + '<span>' + label + '</span>'
                + '<i class="fas fa-check lang-dropdown-check" aria-hidden="true"></i>'
                + '</button>';
        }
        menu.innerHTML = opts;

        trigger.addEventListener('click', e => {
            e.stopPropagation();
            const open = root.classList.toggle('is-open');
            trigger.setAttribute('aria-expanded', String(open));
        });
        // Selection: pick a language, apply it, and close.
        menu.addEventListener('click', e => {
            const opt = e.target.closest('.lang-dropdown-option');
            if (!opt) return;
            applyLang(opt.dataset.value);
            closeLangDropdown(root);
        });
        // Click-outside / Esc to dismiss.
        document.addEventListener('click', e => {
            if (root.classList.contains('is-open') && !root.contains(e.target)) closeLangDropdown(root);
        });
        document.addEventListener('keydown', e => {
            if (e.key === 'Escape' && root.classList.contains('is-open')) {
                closeLangDropdown(root);
                trigger.focus();
            }
        });
    }

    let saved = null;
    try { saved = localStorage.getItem(LANG_KEY); } catch { }
    const lang = saved || detectLang();
    // English pages already carry the right copy — only rewrite when needed.
    if (lang !== 'en' || saved) applyLang(lang);
    else syncLangDropdown('en');
}
